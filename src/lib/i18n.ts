export type TranslationKey = keyof typeof en;

const DICTIONARIES: Record<Language, typeof en> = { en, tr };

export function translator(language: Language) {
  const dictionary = DICTIONARIES[language] ?? en;
  return (key: TranslationKey, vars?: Record<string, string>): string => {
    const value = dictionary[key] ?? en[key];
    if (!vars) return value;
    return Object.entries(vars).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, v), value);
  };
}

export type Translate = ReturnType<typeof translator>;
